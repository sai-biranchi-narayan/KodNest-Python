#int
a = 10
print(type(a), a)

#float
b = 10.85
print(type(b), b)

#bool
c = True # False
print(type(c), c)

#str
d = "hello" # " "
print(type(d), d)

#list
e = [1, 2, 3, 4, 5]
print(type(e), e)

#tuple
f = (1, 2, 3, 4, 5)
print(type(f), f)

#set
g = {1, 2, 3, 4, 5}
print(type(g), g)

#dict
h = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five"}
print(type(h), h)

#complex
i = 1 + 2j
print(type(i), i)

# None
is_vaild = None
print(type(is_vaild), is_vaild)

